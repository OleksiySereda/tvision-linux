static uint16_t table[256];
static int activePage = 0;

static void initTables()
{
    if( activePage != 0 )
        return;
    const char *env = getenv( "TVCODEPAGE" );
    int page = env ? atoi( env ) : 437;
    if( page != 866 && page != 1125 )
        page = 437;

    memcpy( table, lowHalf, sizeof( lowHalf ) );
    memcpy( table + 128, page == 437 ? cp437High : cp866High,
            sizeof( cp437High ) );
    if( page == 1125 )
        memcpy( table + 0xF0, cp1125Tail, sizeof( cp1125Tail ) );
    activePage = page;
}

int codePage()
{
    initTables();
    return activePage;
}

uint32_t toUnicode( unsigned char c )
{
    initTables();
    return table[c];
}

int fromUnicode( uint32_t u )
{
    initTables();
    if( u >= 0x20 && u < 0x7F )
        return int( u );
    for( int i = 0x80; i < 256; i++ )
        if( table[i] == u )
            return i;
    return -1;
}

